class OLED:
    def __init__(self, busno=1, addr=0x3C):
        self.bus = SMBus(busno)
        self.addr = addr
        self.buf = bytearray(WIDTH * PAGES)

    def close(self):
        self.bus.close()

    def write_cmd(self, *cmds):
        msg = i2c_msg.write(self.addr, bytes([0x00, *cmds]))
        self.bus.i2c_rdwr(msg)

    def write_data(self, data):
        for i in range(0, len(data), 16):
            msg = i2c_msg.write(self.addr, bytes([0x40]) + bytes(data[i:i+16]))
            self.bus.i2c_rdwr(msg)

    def init(self):
        self.write_cmd(
            0xAE,
            0xD5, 0x80,
            0xA8, 0x3F,
            0xD3, 0x00,
            0x40,
            0x8D, 0x14,
            0x20, 0x00,
            0xA1,
            0xC8,
            0xDA, 0x12,
            0x81, 0xCF,
            0xD9, 0xF1,
            0xDB, 0x40,
            0xA4,
            0xA6,
            0x2E,
            0xAF
        )

    def show(self):
        self.write_cmd(0x21, 0, WIDTH - 1, 0x22, 0, PAGES - 1)
        self.write_data(self.buf)

    def clear(self):
        self.buf[:] = b'\x00' * len(self.buf)

    def set_pixel(self, x, y, on=True):
        if not (0 <= x < WIDTH and 0 <= y < HEIGHT):
            return
        page = y // 8
        bit = y % 8
        idx = page * WIDTH + x
        if on:
            self.buf[idx] |= (1 << bit)
        else:
            self.buf[idx] &= ~(1 << bit)

    def draw_char(self, x, y, ch):
        glyph = FONT.get(ch.upper(), FONT['?'])
        for col, bits in enumerate(glyph):
            for row in range(7):
                if bits & (1 << row):
                    self.set_pixel(x + col, y + row, True)

    def draw_text(self, x, y, text):
        x0 = x
        for ch in text:
            if ch == '\n':
                x = x0
                y += 8
                continue
            self.draw_char(x, y, ch)
            x += 6   # 5 pixels + 1 spacing

if __name__ == "__main__":
    oled = OLED(BUS, ADDR)
    oled.init()
    oled.clear()

    oled.draw_text(0, 0,  "HELLO")
    oled.draw_text(0, 16, "OLED 128X64")
    oled.draw_text(0, 32, "ADDR 0X3C")
    oled.draw_text(0, 48, "I2C RAW OK")

    oled.show()
    oled.close()
